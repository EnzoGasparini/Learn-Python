# Detective de tipo

"""
Mostrá de qué tipo de dato es cada uno de estos valores: 5, 5.0, "5", True y None.
"""

numero = 5
numero_con_decimal = 5.0
numero_texto = "5"
valor_booleano = True
valor_none = None

print(type(numero))
print(type(numero_con_decimal))
print(type(numero_texto))
print(type(valor_booleano))
print(type(valor_none))
